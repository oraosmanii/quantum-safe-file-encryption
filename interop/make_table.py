#!/usr/bin/env python3
"""Generate the RQ4 booktabs tables from the interoperability CSV files.

Uses only the Python standard library so it can run inside the pinned image.
"""
from __future__ import annotations

import argparse
import csv
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOOLS = ("gpg", "sq", "gopenpgp")


def read_csv(path):
    if not path.is_file():
        raise SystemExit(f"missing required input: {path}")
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def esc(value):
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
                 ("#", r"\#"), ("_", r"\_"), ("$", r"\$"), ("{", r"\{"), ("}", r"\}")):
        value = str(value).replace(a, b)
    return value


def tabular(headers, aligns, rows, note):
    lines = [f"% {note}", "% Generated by interop/make_table.py from results/interop/.",
             r"\begin{tabular}{" + "".join(aligns) + "}", r"\toprule",
             " & ".join(headers) + " " + chr(92) * 2, r"\midrule"]
    lines.extend(" & ".join(row) + " " + chr(92) * 2 for row in rows)
    lines.extend([r"\bottomrule", r"\end{tabular}", ""])
    return "\n".join(lines)


def matrix_tex(rows):
    # Each repeat has a result per directed pair and key type. Mark unstable cells explicitly.
    grouped = defaultdict(list)
    for r in rows:
        grouped[(r["key_type"], r["encryptor"], r["decryptor"])].append(r)
    out = ["% RQ4 interoperability: rows encrypt, columns decrypt.",
           "% A superscript * marks disagreement across repeats."]
    for key_type in ("classical", "pqc"):
        table = []
        for enc in TOOLS:
            cells = [esc(enc)]
            for dec in TOOLS:
                observations = grouped.get((key_type, enc, dec), [])
                outcomes = [(r["result"], r["stage_reached"] if r["result"] != "pass" else "done")
                            for r in observations]
                if not observations:
                    cell = "--"
                else:
                    stages = Counter(stage for result, stage in outcomes if result != "pass")
                    marks = Counter(result for result, _ in outcomes)
                    if len(set(outcomes)) > 1:
                        cell = r"\textbf{varies}$^{*}$"
                    elif marks.get("pass"):
                        cell = r"$\surd$"
                    else:
                        stage = stages.most_common(1)[0][0] if stages else "?"
                        cell = r"$\times$\ " + esc(stage)
                cells.append(cell)
            table.append(cells)
        out.append(r"\paragraph{" + key_type.capitalize() + r" keys}")
        out.append(tabular([r"Encryptor $\backslash$ decryptor"] + [esc(t) for t in TOOLS],
                           ["l", "c", "c", "c"], table,
                           f"RQ4 directed interoperation, {key_type} keys"))
    out.append(r"\emph{Note:} $\surd$ = successful decryption with matching SHA-256; $\times$ = failure stage; * = repeats disagree.")
    return "\n\n".join(out) + "\n"


def packet_tex(rows):
    by_tool = {tool: {} for tool in TOOLS}
    for r in rows:
        if r["key_type"] != "pqc":
            continue
        item = by_tool.setdefault(r["producer"], {})
        obj = r["object"]
        if obj == "cert":
            if r["key_version"]:
                item["key_version"] = r["key_version"]
            if r["pk_algo_id"]:
                item["key_algo"] = r["pk_algo_id"]
        elif obj == "ciphertext":
            for name, dest in (("pkesk_version", "pkesk"), ("seipd_version", "seipd")):
                if r[name]:
                    item[dest] = r[name]
    table = []
    for tool in TOOLS:
        x = by_tool.get(tool, {})
        table.append([esc(tool), esc(x.get("key_version", "--")), esc(x.get("key_algo", "--")),
                      esc(x.get("pkesk", "--")), esc(x.get("seipd", "--"))])
    return tabular(["Producer", "Key packet", "Encryption PK algo ID", "PKESK version", "SEIPD version / data packet"],
                   ["l", "c", "c", "c", "c"], table,
                   "PQC packet fields; values are taken from key/ciphertext dumps in packets.csv")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", type=Path, default=ROOT / "results" / "interop")
    ap.add_argument("--out", type=Path, default=ROOT / "tables")
    args = ap.parse_args()
    matrix = read_csv(args.results / "matrix.csv")
    packets = read_csv(args.results / "packets.csv")
    expected = 3 * 3 * 2 * 3
    if len(matrix) != expected:
        raise SystemExit(f"matrix has {len(matrix)} rows; expected {expected} (3 tools x 3 tools x 2 keys x 3 repeats)")
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "interop_matrix.tex").write_text(matrix_tex(matrix), encoding="utf-8", newline="\n")
    (args.out / "interop_packets.tex").write_text(packet_tex(packets), encoding="utf-8", newline="\n")
    print(f"wrote {args.out / 'interop_matrix.tex'} and {args.out / 'interop_packets.tex'}")


if __name__ == "__main__":
    main()
