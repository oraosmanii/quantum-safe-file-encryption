"""Make the LaTeX tables for RQ1-RQ3 and the environment from results/.

Runs on the host, after analysis/sanity.py:
    python3 analysis/tables.py [--phase full|pilot] [--results DIR] [--out DIR] [--allow-missing]

Reads only the results directory, writes tables/<name>.tex (booktabs, \\input into the paper):
- key_sizes: public key and encryption-subkey packet sizes per mode (RQ1)
- ratio_time, ratio_cpu: PQ/classical ratio of wall time and of CPU time, median with
  95% bootstrap CI, per matched condition (RQ2, RQ3)
- decompose_time, decompose_cpu: a + b * recipients + c * bytes per mode (RQ2, RQ3)
- environment: machine, Docker, and tool versions from env.json
The interop tables (interop_*.tex) are made by Person B's interop/make_table.py.
"""

import argparse
import sys
from pathlib import Path

import data
import stats


def tex(text):
    """Escape the LaTeX special characters that occur in our values."""
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("#", r"\#"),
                 ("_", r"\_"), ("$", r"\$"), ("{", r"\{"), ("}", r"\}")):
        text = text.replace(a, b)
    return text


def tabular(columns, rows, caption_comment):
    """A booktabs tabular; columns is a list of (header, align)."""
    lines = [f"% {caption_comment}",
             f"% Generated by analysis/tables.py from results/; do not edit by hand.",
             r"\begin{tabular}{" + "".join(a for _, a in columns) + "}", r"\toprule",
             " & ".join(h for h, _ in columns) + r" \\", r"\midrule"]
    lines += [" & ".join(row) + r" \\" for row in rows]
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(lines)


def key_sizes(results, phase):
    df = data.key_sizes(results)
    rows = []
    for mode in data.MODES:
        g = df[df["mode"] == mode]
        if g.empty:
            continue
        pk = f"{g['public_key_bytes'].min():,}"
        if g["public_key_bytes"].max() != g["public_key_bytes"].min():
            pk += f"--{g['public_key_bytes'].max():,}"
        sub = g["enc_subkey_packet_bytes"].dropna()
        rows.append([tex(mode), pk, f"{int(sub.median()):,}" if len(sub) else "--"])
    return tabular([("mode", "l"), ("public key (bytes)", "r"), ("enc.\\ subkey packet (bytes)", "r")],
                   rows, "RQ1: public key size per mode (age: recipient string; gpg: exported cert)")


def ratio_rows(r):
    order = {s: i for i, s in enumerate(data.SIZES)}
    pos = {"na": 0, "only": 1, "first": 1, "last": 2}
    r = r.assign(o1=r["size_id"].map(order), o3=r["recipient_position"].map(pos))
    rows = []
    keys = ["size_id", "n_recipients", "op", "recipient_position"]
    for key, g in r.sort_values(["o1", "n_recipients", "o3"]).groupby(keys, sort=False):
        size_id, n, op, position = key
        what = op if op == "encrypt" else f"decrypt ({position})"
        cells = [size_id, str(n), what]
        for tool in data.PAIRS:
            t = g[g["tool"] == tool]
            cells.append("--" if t.empty else
                         f"{t['ratio'].iloc[0]:.2f} [{t['ci_low'].iloc[0]:.2f}, {t['ci_high'].iloc[0]:.2f}]")
        rows.append(cells)
    return rows


def ratio_table(r, what):
    heads = [("size", "l"), ("$n$", "r"), ("operation", "l")]
    heads += [(f"{tex(pq)} / {tex(cl)}", "r") for pq, cl in data.PAIRS.values()]
    return tabular(heads, ratio_rows(r),
                   f"PQ/classical ratio of median {what}, 95% bootstrap CI "
                   f"({stats.BOOTSTRAP_ITERATIONS:,} iterations)")


def ratio_time(results, phase):
    return ratio_table(stats.ratios(data.timing(results, phase), "wall_s"), "wall time")


def ratio_cpu(results, phase):
    return ratio_table(stats.ratios(data.resources(results, phase), "cpu_usec"), "CPU time")


def decompose_table(df, unit, scale, what):
    rows = []
    for _, r in df.iterrows():
        rows.append([tex(r["mode"]), tex(r["variant"].replace("_", " ")),
                     f"{r['a'] * scale:.2f}", f"{r['b_per_recipient'] * scale:.3f}",
                     f"{r['c_per_byte'] * scale * 2**20:.3f}", f"{r['r2']:.3f}"])
    return tabular([("mode", "l"), ("operation", "l"), (f"$a$ ({unit})", "r"),
                    (f"$b$ ({unit}/recipient)", "r"), (f"$c$ ({unit}/MiB)", "r"), ("$R^2$", "r")],
                   rows, f"cost decomposition of {what}: a + b * recipients + c * file bytes, "
                         f"least squares over all runs")


def decompose_time(results, phase):
    return decompose_table(stats.decompose(data.timing(results, phase), "wall_s"), "ms", 1e3,
                           "wall time")


def decompose_cpu(results, phase):
    return decompose_table(stats.decompose(data.resources(results, phase), "cpu_usec"), "ms",
                           1e-3, "CPU time")


def first_line(value):
    return value.splitlines()[0].removeprefix("* ").strip() if value else "unknown"


def docker_version(text):
    """'Docker Engine 29.8.2 (Docker Desktop 4.95.0)' from the `docker version` output."""
    server = engine = None
    in_engine = False
    for line in (text or "").splitlines():
        s = line.strip()
        if s.startswith("Server:"):
            server = s.removeprefix("Server:").strip()
        elif s.startswith("Engine:"):
            in_engine = True
        elif in_engine and s.startswith("Version:"):
            engine = s.removeprefix("Version:").strip()
            break
    if engine is None:
        return first_line(text)
    return f"Docker Engine {engine}" + (f" ({server})" if server else "")


def environment(results, phase):
    env = data.env(results)
    host, docker, tools = env["host"], env["docker"], env["tools"]
    gib = f"{host['ram_bytes'] / 2**30:.1f} GiB" if host.get("ram_bytes") else "unknown"
    rows = [("CPU", f"{host.get('cpu_model')} ({host.get('cores')} logical CPUs)"),
            ("RAM visible to Docker", gib),
            ("Host OS", host.get("os")), ("Kernel", host.get("kernel")),
            ("Docker", docker_version(docker.get("version"))),
            ("Container OS", env["container"].get("os")),
            ("git commit", (env.get("git_commit") or "unknown")[:12])]
    rows += [(name, first_line(tools.get(name) or "")) for name in
             ("age", "gpg", "libgcrypt", "sq", "openssl", "gopenpgp", "hyperfine", "python")]
    return tabular([("item", "l"), ("value", "l")],
                   [[tex(k), tex(str(v))] for k, v in rows],
                   f"measurement environment, captured {env.get('captured_utc')}")


TABLES = {
    "key_sizes": key_sizes,
    "ratio_time": ratio_time,
    "ratio_cpu": ratio_cpu,
    "decompose_time": decompose_time,
    "decompose_cpu": decompose_cpu,
    "environment": environment,
}


def run(phase="full", results=data.RESULTS, out=data.TABLES, allow_missing=False, only=None):
    """Write every table; return False if one could not be made."""
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    ok = True
    for name, make in TABLES.items():
        if only and name not in only:
            continue
        try:
            text = make(results, phase)
        except data.DataError as e:
            print(f"{'SKIP' if allow_missing else 'FAIL'}  {name}: {e}")
            ok = ok and allow_missing
            continue
        (out / f"{name}.tex").write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {out / name}.tex")
    return ok


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--phase", choices=("full", "pilot"), default="full")
    parser.add_argument("--results", default=str(data.RESULTS))
    parser.add_argument("--out", default=str(data.TABLES))
    parser.add_argument("--allow-missing", action="store_true",
                        help="skip tables whose data is missing (development only)")
    parser.add_argument("--only", nargs="+", choices=sorted(TABLES))
    args = parser.parse_args()
    sys.exit(0 if run(args.phase, args.results, args.out, args.allow_missing, args.only) else 1)


if __name__ == "__main__":
    main()
